#!/usr/bin/env python3
"""Regenerate the inventory in .claude/README.md from the files in .claude/.

Skills and agents come from their frontmatter, hooks from settings.json and the
header comment on line 2 of each hook script, permissions from settings.json.
Only the text between the two markers in README.md is replaced.

Usage: .claude/bom.py          rewrite README.md if it is out of date
       .claude/bom.py --check  exit 1 if README.md is out of date, change nothing
"""
import json, re, sys
from pathlib import Path

ROOT = Path(__file__).resolve().parent
README = ROOT / "README.md"
START, END = "<!-- bom:start (generated by .claude/bom.py; do not edit) -->", "<!-- bom:end -->"


def frontmatter(path):
    text = path.read_text()
    m = re.match(r"---\n(.*?)\n---", text, re.S)
    out = {}
    for line in (m.group(1).splitlines() if m else []):
        k, sep, v = line.partition(":")
        if sep and not line.startswith(" "):
            out[k.strip()] = v.strip().strip('"')
    return out


def cell(s):
    return s.replace("|", "\\|").replace("\n", " ")


def table(head, rows):
    lines = ["| " + " | ".join(head) + " |", "| " + " | ".join("---" for _ in head) + " |"]
    lines += ["| " + " | ".join(cell(c) for c in r) + " |" for r in rows]
    return "\n".join(lines) if rows else "None."


def hook_summary(script):
    if not script.exists():
        return "(script missing)"
    lines = script.read_text().splitlines()
    comment = lines[1].lstrip("# ").strip() if len(lines) > 1 and lines[1].startswith("#") else ""
    text = comment.split(": ", 1)[1] if ": " in comment else comment
    return text[:1].upper() + text[1:] if text else "(no header comment)"


def generate():
    skills = [frontmatter(p) | {"_dir": p.parent.name} for p in sorted(ROOT.glob("skills/*/SKILL.md"))]
    agents = [frontmatter(p) | {"_file": p.name} for p in sorted(ROOT.glob("agents/*.md"))]
    settings = json.loads((ROOT / "settings.json").read_text())

    hooks = []
    for event, groups in settings.get("hooks", {}).items():
        for g in groups:
            for h in g.get("hooks", []):
                cmd = h.get("command", "")
                m = re.search(r"\.claude/(hooks/[^\"' ]+)", cmd)
                script = m.group(1) if m else cmd
                hooks.append([f"`{event}`", g.get("matcher", "all"), f"`{script}`",
                              hook_summary(ROOT / script) if m else ""])

    parts = [
        "## Skills\n",
        table(["Skill", "Arguments", "Use it for"],
              [[f"`/{s.get('name', s['_dir'])}`", f"`{s['argument-hint']}`" if s.get("argument-hint") else "", s.get("description", "")] for s in skills]),
        "\n## Agents\n",
        table(["Agent", "Tools", "Use it for"],
              [[f"`{a.get('name', a['_file'])}`", a.get("tools", "all").strip("[]").replace('"', ""), a.get("description", "")] for a in agents]),
        "\n## Hooks\n",
        table(["Event", "Matcher", "Script", "Does"], hooks),
        "\n## Permissions\n",
        "Allowed without a prompt:\n",
        "\n".join(f"- `{p}`" for p in settings.get("permissions", {}).get("allow", [])) or "None.",
    ]
    return "\n".join(parts)


def main():
    text = README.read_text()
    if START not in text or END not in text:
        sys.exit(f"{README} has no {START} ... {END} markers")
    head, rest = text.split(START, 1)
    _, tail = rest.split(END, 1)
    new = f"{head}{START}\n\n{generate()}\n\n{END}{tail}"
    if new == text:
        return
    if "--check" in sys.argv:
        print(".claude/README.md is out of date; run .claude/bom.py")
        sys.exit(1)
    README.write_text(new)


main()
